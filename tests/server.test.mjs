test('single byte ranges, suffixes and invalid ranges', () => {
  assert.deepEqual(parseRange('bytes=10-20', 100), { start: 10, end: 20 });
  assert.deepEqual(parseRange('bytes=90-', 100), { start: 90, end: 99 });
  assert.deepEqual(parseRange('bytes=-10', 100), { start: 90, end: 99 });
  assert.deepEqual(parseRange('bytes=90-999', 100), { start: 90, end: 99 });
  for (const value of ['bytes=100-', 'bytes=20-10', 'bytes=-0', 'bytes=-', 'bytes=1-3,5-8', 'invalid']) assert.equal(parseRange(value, 100), false);
  assert.equal(parseRange(undefined, 100), null);
});


import test from 'node:test';
import assert from 'node:assert/strict';
import { stat } from 'node:fs/promises';
import { createServer, parseRange } from '../server.mjs';

test('single byte ranges, suffixes and invalid ranges', () => {
  assert.deepEqual(parseRange('bytes=10-20', 100), { start: 10, end: 20 });
  assert.deepEqual(parseRange('bytes=90-', 100), { start: 90, end: 99 });
  assert.deepEqual(parseRange('bytes=-10', 100), { start: 90, end: 99 });
  assert.deepEqual(parseRange('bytes=90-999', 100), { start: 90, end: 99 });
  for (const value of ['bytes=100-', 'bytes=20-10', 'bytes=-0', 'bytes=-', 'bytes=1-3,5-8', 'invalid']) assert.equal(parseRange(value, 100), false);
  assert.equal(parseRange(undefined, 100), null);
});

test('serves app and seekable audio without exposing arbitrary files', async t => {
  const server = createServer();
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const base = `http://127.0.0.1:${server.address().port}`;
  const page = await fetch(base);
  assert.equal(page.status, 200);
  const html = await page.text();
  assert.match(html, /Fatiha/);
  assert.match(html, /id="open-display-settings"/);
  assert.match(html, /id="display-settings"/);
  assert.match(html, /id="toggle-reading" type="checkbox"/);
  assert.match(html, /id="word-preview" type="checkbox"/);
  assert.match(html, /class="talim-visual"/);
  assert.match(html, /class="verse-chips"/);
  assert.match(html, /id="open-editor" class="quiet" hidden/);
  assert.match(html, /id="repeat-gap"[^>]*hidden/);
  assert.match(html, /<dialog id="editor"/);
  assert.doesNotMatch(html, /word-preview-note|player-tip-text|preview-details|class="intro"|id="alignment-note"/);
  assert.match(html, /<h1 class="lesson-title">Fatiha Suresi<\/h1>/);
  const preview = await fetch(`${base}/word-preview.json`);
  assert.equal(preview.status, 200);
  assert.equal((await preview.json()).words.length, 34);
  assert.equal((await fetch(`${base}/word-preview.mjs`)).status, 200);
  assert.equal((await fetch(`${base}/verse-playback.mjs`)).status, 200);
  assert.equal((await fetch(`${base}/study-groups.mjs`)).status, 200);
  const silence = await fetch(`${base}/preview-silence.json`);
  assert.equal(silence.status, 200);
  assert.equal((await silence.json()).silences.length, 6);
  const final = await fetch(`${base}/final-preview.json`);
  assert.equal(final.status, 200);
  assert.deepEqual((await final.json()).overrides.map(word => word.id), ['7:6', '7:7', '7:8']);
  assert.equal((await fetch(`${base}/data/final-phrase-local/diagnostic-raw.json`)).status, 404);
  assert.equal((await fetch(`${base}/data/alignment-local-001-verified/asr-raw.json`)).status, 404);
  assert.equal((await fetch(`${base}/package.json`)).status, 404);
  assert.equal((await fetch(`${base}/%2e%2e/server.mjs`)).status, 404);
  assert.equal((await fetch(base, { method: 'POST' })).status, 405);
  const size = (await stat(new URL('../001.mp3', import.meta.url))).size;
  const response = await fetch(`${base}/001.mp3`, { headers: { Range: 'bytes=0-99' } });
  assert.equal(response.status, 206);
  assert.equal(response.headers.get('content-range'), `bytes 0-99/${size}`);
  assert.equal((await response.arrayBuffer()).byteLength, 100);
  const invalid = await fetch(`${base}/001.mp3`, { headers: { Range: `bytes=${size}-` } });
  assert.equal(invalid.status, 416);
  const head = await fetch(`${base}/001.mp3`, { method: 'HEAD' });
  assert.equal(head.headers.get('content-length'), String(size));
  assert.equal((await head.text()).length, 0);
});
